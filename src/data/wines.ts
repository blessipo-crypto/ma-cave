import { WineReference, MerchantSite } from "../types/wine";

function makeMerchants(query: string, includeFrenchAuction = true): MerchantSite[] {
  const q = encodeURIComponent(query);
  const list: MerchantSite[] = [
    {
      name: "Wine-Searcher",
      url: `https://www.wine-searcher.com/find/${q}`,
      type: "Comparateur",
    },
    {
      name: "Vinatis",
      url: `https://www.vinatis.com/recherche?search=${q}`,
      type: "Caviste en ligne",
    },
    {
      name: "Lavinia",
      url: `https://www.lavinia.com/fr/catalogsearch/result/?q=${q}`,
      type: "Caviste en ligne",
    },
  ];
  if (includeFrenchAuction) {
    list.push({
      name: "iDealwine",
      url: `https://www.idealwine.com/fr/acheter-vin/${q}.jsp`,
      type: "Enchères & Grands Crus",
    });
    list.push({
      name: "Millésima",
      url: `https://www.millesima.fr/catalogsearch/result/?q=${q}`,
      type: "Enchères & Grands Crus",
    });
  }
  return list;
}

